  String _t(String key) {
    final lang = _translations[languageCode] ?? _translations['it']!;
    return lang[key] ?? _translations['it']![key] ?? key;
  }

  /// Testo tradotto per una chiave (usato dalle stringhe delle ultime schermate).
  String t(String key) => _t(key);

  /// Testo con segnaposto: `{n}`, `{d}`... sostituiti dai [params].
  String fmt(String key, Map<String, String> params) {
    var text = _t(key);
    params.forEach((k, v) => text = text.replaceAll('{$k}', v));
    return text;
  }

  /// Singolare/plurale: usa `<base>One` per 1 e `<base>Many` (con `{n}`) altrimenti.
  String count(String base, int n) =>
      n == 1 ? _t('${base}One') : fmt('${base}Many', {'n': '$n'});

  /// Elenco separato da virgole (es. i mesi).
  List<String> list(String key) => _t(key).split(',');

